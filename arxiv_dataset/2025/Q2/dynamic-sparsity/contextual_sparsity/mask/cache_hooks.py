from functools import partial
from typing import Callable, List, Optional, Union

import torch
from omegaconf import DictConfig
from torch import nn

from contextual_sparsity.hw_simulator.simulator import HardwareSimulator
from contextual_sparsity.mask.cache_aware_methods import (
    cache_aware_reweighting_approximate,
    cache_aware_reweighting_current_cache,
)
from contextual_sparsity.mask.hooks import MaskingHook


def parse_and_detach_mask(mask):
    mask = mask.detach().clone()
    # Some models collapse the batch dimension, some don't.
    if mask.ndim == 3:
        assert mask.shape[0] == 1, "Currently only supporting batch size==1"
        mask = mask.squeeze()
    return mask


class MaskingFuncWithCacheWrite(nn.Module):
    def __init__(self, masking_hook: MaskingHook, write_callback_fn: Callable):
        """
        Args:
        -----------
        masking_hook: MaskingHook
            An instance of the MaskingHook class containing the masking function.
        write_callback_fn: function
            An callback function from an HardwareSimulator instance providing access to the cache write functionality.
        """

        super().__init__()
        self.masking_func = masking_hook.masking_func
        self.mask_rows_of = masking_hook.mask_rows_of
        self.mask_cols_of = masking_hook.mask_cols_of
        self.write_callback_fn = write_callback_fn

    def forward(self, x: torch.Tensor) -> torch.BoolTensor:
        """
        Applies the masking function on the input tensor and calls the cache write callback function for each resultant
        mask. The masks are generated by iterating over the sequence axis of the provided input tensor.
        Note: Currently only supports column masking operations.

        Args:
        -----------
        x: torch.Tensor
            Input tensor from previous layer.

        Returns:
        -----------
        torch.BoolTensor
            Resultant mask after applying the masking function.
        """
        mask = self.masking_func(x)
        mask = parse_and_detach_mask(mask)
        # Iterate over context and call the HW_simulator, to simulate sequential token generation
        for i, cur_mask in enumerate(mask):
            assert self.mask_cols_of is not None
            self.write_callback_fn(self.mask_cols_of[0], cur_mask=cur_mask)
        return mask


class MaskingFuncWithCacheReadWrite(nn.Module):
    def __init__(
        self,
        masking_hook: MaskingHook,
        write_callback_fn: Callable,
        read_callback_fn: Callable,
        cache_aware_masking_method: str,
        kwargs,
    ):
        """
        Args:
        -----------
        masking_hook: MaskingHook
            An instance of the MaskingHook class containing the masking function.
        write_callback_fn: function
            An callback function from an HardwareSimulator instance providing access to the cache write functionality.
        read_callback_fn: function
            An callback function from an HardwareSimulator instance providing access to the cache read functionality.
        cache_aware_masking_method: str
            The name of the cache-aware masking method to be used to condition the masking choice based on information
            from the cache (e.g.: current status, past statistics, expected future content).
        """

        super().__init__()
        if isinstance(masking_hook.masking_func, nn.Sequential):
            self.masking_func_prediction = masking_hook.masking_func[:-1]
            self.masking_func_binarization = masking_hook.masking_func[-1:]
        else:
            self.masking_func_prediction = lambda x: x
            self.masking_func_binarization = masking_hook.masking_func
        self.mask_rows_of = masking_hook.mask_rows_of
        self.mask_cols_of = masking_hook.mask_cols_of
        self.write_callback_fn = write_callback_fn
        self.read_callback_fn = read_callback_fn

        self.cache_aware_masking_method = cache_aware_masking_method
        if self.cache_aware_masking_method == "none":
            self.masking_func_cache_aware_update = (
                lambda mask, cache, **kw: mask
            )  # identity function, for debugging.
        elif self.cache_aware_masking_method == "weighting_current_cache":
            self.masking_func_cache_aware_update = partial(
                cache_aware_reweighting_current_cache, **kwargs
            )
        elif self.cache_aware_masking_method == "approximate_caching":
            self.masking_func_cache_aware_update = partial(
                cache_aware_reweighting_approximate, **kwargs
            )
        else:
            raise ValueError(
                f"Unsupported cache-aware masking method: {self.cache_aware_masking_method}"
            )

    def forward(self, x: torch.Tensor) -> torch.BoolTensor:
        """
        Computes the mask for the current layer using the specified cache-aware method.
        For every token in the sequence, reads the current cache, computes the prediction scores, updates the cache based on
        those predictions along with other relevant factors, binarize the computed scores to get a binary mask.
        Writes back the updated cache via a callback function.
        Finally, concatenates all individual masks together and returns the resulting masked output tensor.

        Args:
        -----------
        x : torch.Tensor
            Input tensor from previous layer.

        Returns:
        -----------
        torch.BoolTensor
            Resultant mask after applying the masking function.

        """
        assert torch.isnan(x).any().item() is False, torch.isnan(x).any()
        input_shape = x.shape
        end_squeeze = False
        if x.ndim == 2:
            x = x.unsqueeze(0)
            end_squeeze = True
        assert x.ndim == 3, x.shape

        # Iterate over all tokens, read cache, predict mask, write cache
        mask = []
        scores = self.masking_func_prediction(
            x
        )  # once we implement a cache-aware prediction function, this must be moved back inside the loop
        for i in range(x.shape[-2]):
            cur_input = x[:, i : i + 1]

            # Read cache
            cur_cache, cache_stats = self.read_callback_fn(self.mask_cols_of[0])
            if cur_cache is None:
                cur_cache = torch.zeros(
                    cur_input.shape[-1], dtype=torch.bool, device=cur_input.device
                )
                cache_stats = torch.zeros(
                    cur_input.shape[-1], dtype=torch.bool, device=cur_input.device
                )

            # Get additional arguments
            kwargs = dict()
            if self.cache_aware_masking_method == "weighting_current_cache":
                kwargs["t"] = i
            if self.cache_aware_masking_method == "approximate_caching":
                kwargs["cache_stats"] = cache_stats

            # Cache-aware masking and binarization
            score = scores[:, i : i + 1]
            score = self.masking_func_cache_aware_update(score, cur_cache, **kwargs)
            cur_mask = self.masking_func_binarization(score)
            mask.append(cur_mask)

            # Write cache
            assert self.mask_cols_of is not None
            self.write_callback_fn(self.mask_cols_of[0], cur_mask=parse_and_detach_mask(cur_mask))

        mask = torch.cat(mask, dim=-2)
        mask = mask.squeeze(0) if end_squeeze else mask
        assert mask.shape == input_shape and mask.dtype == torch.bool, (
            mask.shape,
            input_shape,
            mask.dtype,
        )
        return mask

    def get_next_use_belady(
        self, input: torch.FloatTensor, never_used_multiplier: int = None
    ) -> torch.LongTensor:
        """
        Batch computation of next use for each neuron for oracles based on FIFU (Belady).

        Args:
        -----------
        input: torch.FloatTensor (1, seq_len, intermediate_dim)
            Input activations for the mask.
        never_used_multiplier: int, optional
            Multiplier to set a specific high value to neurons that will never be used again in this sequence.

        Returns:
        -----------
        torch.LongTensor (1, seq_len, intermediate_dim)
            Next use of each neuron in the sequence based on predicted
            masks. Minimum value is 1 (neuron active in next token's mask).
            Maximum value for neurons that will never be used again is set to seq_length * never_used_multiplier if the
            multiplier is set, otherwise as the length of future sequence + 1.

        """
        bsz, seq_len, intermediate_dim = input.shape

        # Get binary masks and append a fake token with all True values to simulate "infinite" horizon.
        all_masks = torch.ones(
            (bsz, seq_len + 1, intermediate_dim), dtype=torch.bool, device=input.device
        )
        all_masks[:, :-1] = self.masking_func_binarization(self.masking_func_prediction(input))

        # Find next use for each neuron at each time-step.
        next_use = torch.zeros(input.shape, dtype=torch.int64, device=input.device)
        for i in range(0, seq_len):
            next_use[:, i] = torch.max(all_masks[:, i + 1 :], dim=1).indices + 1

        # Set high value for neurons that will never be used again.
        if never_used_multiplier:
            arange = torch.arange(seq_len, 0, -1, device=input.device)
            never_used = next_use == arange[None, :, None].repeat(1, 1, intermediate_dim)
            next_use[never_used] = seq_len * never_used_multiplier

        assert torch.all(next_use != 0)
        assert next_use.shape == input.shape, (next_use.shape, input.shape)
        return next_use


def link_masking_hooks_with_cache(
    masking_hooks: List[MaskingHook],
    hw_simulator: HardwareSimulator,
    method: Optional[str] = None,
    kwargs: Optional[Union[dict, DictConfig]] = None,
) -> List[MaskingHook]:
    """
    Links each provided `MaskingHook` instance to a corresponding caching mechanism implemented by the hardware
    simulator (i.e., `HardwareSimulator`).
    This is done by wrapping the masking function into a new torch module which also writes the mask to cache, and
    optionally reads the cache first to condition the masking choice.
    The choice between including only writing or reading/writing operations depends on whether a specific cache-aware
    method is passed as parameter.

    Args:
    -----------
    masking_hooks : List[MaskingHook]
        list of MaskingHook instances that need to be linked with cache mechanisms.
    hw_simulator : HardwareSimulator
        A hardware simulator object implementing methods to interact with memory.
        This includes functions like 'write_to_memory' and 'read_from_memory'.
    method : str, optional
        An optional string representing the name of a particular cache-aware method.

    Returns:
    -----------
    List[MaskingHook]
        A modified list of input MaskingHook objects where every one has been assigned a respective caching
        mechanism based on the chosen strategy.

    """
    write_callback_fn = hw_simulator.write_to_memory
    read_callback_fn = hw_simulator.read_from_memory

    for masking_hook in masking_hooks:
        if method is None:
            masking_func = MaskingFuncWithCacheWrite(masking_hook, write_callback_fn)
        else:
            assert hw_simulator.cache_strategy != "belady", (
                "Cache-aware masking currently not supported with FIFU eviction strategy! "
                "The belady horizons (and cache states) are only rolled out at the end of the sequence."
            )
            masking_func = MaskingFuncWithCacheReadWrite(
                masking_hook, write_callback_fn, read_callback_fn, method, kwargs
            )
        masking_hook.set_masking_func(masking_func)

    return masking_hooks
